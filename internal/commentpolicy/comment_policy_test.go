package commentpolicy

import (
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"testing"
)

var (
	goDirective     = regexp.MustCompile(`^//go:[a-z0-9]+(?:[ \t].*)?$`)
	lineDirective   = regexp.MustCompile(`^(?://line .*:[1-9][0-9]*(?::[1-9][0-9]*)?|/\*line .*:[1-9][0-9]*(?::[1-9][0-9]*)?\*/)$`)
	generatedMarker = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)
)

func TestRepositoryGoFilesContainOnlyPolicyComments(t *testing.T) {
	root := repositoryRoot(t)

	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() && path != root && excludedDirectory(entry.Name()) {
			return filepath.SkipDir
		}

		if entry.IsDir() || filepath.Ext(path) != ".go" {
			return nil
		}

		return validateFile(path)
	})
	if err != nil {
		t.Fatal(err)
	}
}

func TestValidateFileRejectsProseComments(t *testing.T) {
	filename := filepath.Join(t.TempDir(), "prose.go")
	source := "package prose\n\n// This comment is forbidden.\nvar value int\n"

	if err := os.WriteFile(filename, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}

	err := validateFile(filename)
	if err == nil || !strings.Contains(err.Error(), "This comment is forbidden") {
		t.Fatalf("validateFile() error = %v", err)
	}
}

func TestValidateFileAllowsRecognizedMarkers(t *testing.T) {
	filename := filepath.Join(t.TempDir(), "directives.go")
	source := "// Code generated by policy test. DO NOT EDIT.\n//go:build policy\n//line generated.go:10\npackage directives\n"

	if err := os.WriteFile(filename, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := validateFile(filename); err != nil {
		t.Fatal(err)
	}
}

func repositoryRoot(t *testing.T) string {
	t.Helper()

	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("resolve policy test location")
	}

	return filepath.Clean(filepath.Join(filepath.Dir(filename), "..", ".."))
}

func excludedDirectory(name string) bool {
	switch name {
	case ".git", "dist", "logs", "tmp", "vendor":
		return true
	default:
		return false
	}
}

func validateFile(filename string) error {
	set := token.NewFileSet()

	parsed, err := parser.ParseFile(set, filename, nil, parser.ParseComments|parser.AllErrors)
	if err != nil {
		return fmt.Errorf("parse %s: %w", filename, err)
	}

	for _, group := range parsed.Comments {
		for _, comment := range group.List {
			if allowedComment(comment.Text) {
				continue
			}

			position := set.Position(comment.Pos())

			return fmt.Errorf("%s: forbidden Go comment %q", position, comment.Text)
		}
	}

	return nil
}

func allowedComment(comment string) bool {
	return goDirective.MatchString(comment) || lineDirective.MatchString(comment) || generatedMarker.MatchString(comment)
}
